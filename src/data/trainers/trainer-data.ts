// #region CompoundTrainerData

export class CompoundTrainerData {
  public readonly trainerData: TrainerSlotMap<TrainerData>;
  public readonly title: string;

  /**
   * @param config - The {@linkcode CompositeTrainerConfig} from which the data is generated
   * @param genders - The {@linkcode TrainerGender}s of each Trainer, organized by {@linkcode TrainerSlot}.
   * If a gender isn't specified for a slot, that slot's Trainer will be given a
   * random gender (see {@linkcode TrainerData.initGender}).
   */
  constructor(config: CompositeTrainerConfig, genders: Partial<TrainerSlotMap<NonDefaultTrainerGender>> = {}) {
    for (const [slot, cfg] of Object.entries(config.configs)) {
      const trainerSlot = Number(slot) as NonNullTrainerSlot;
      this.trainerData[slot] = new TrainerData(
        trainerSlot,
        cfg,
        genders[trainerSlot],
        config.useSameSeedForAllTrainers,
        3, // Party size is limited to 3 per Trainer
      );
    }
    this.title = config.combinedTitle;
  }
}

